class KnowledgeStore:
    """知识库 JSON 存储 (原子写 + 实例锁, 首次自动种子)。"""

    # 种子数据版本 — 升级后已有 knowledge.json 会自动重建
    _SEED_VERSION = 8

    def __init__(self) -> None:
        self._lock = threading.Lock()

    def _path(self) -> Path:
        from app.config import settings
        p = settings.data_dir / "user_data" / "knowledge.json"
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    def list_all(self) -> list[dict]:
        p = self._path()
        if not p.exists():
            # 首次启动: 注入种子数据
            seed = _build_seed()
            self._atomic_write(seed)
            return seed
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(data, list):
                # 版本检测: 旧数据无 SVG 或版本不匹配 → 重建
                needs_rebuild = False
                if data and isinstance(data[0], dict):
                    ver = data[0].get("_seed_version", 1)
                    if ver < self._SEED_VERSION:
                        needs_rebuild = True
                if needs_rebuild:
                    logger.info("knowledge.json seed version outdated, rebuilding...")
                    seed = _build_seed()
                    self._atomic_write(seed)
                    return seed
                return data
        except Exception as e:  # noqa: BLE001
            logger.warning("knowledge.json malformed: %s", e)
        return []

    def _atomic_write(self, items: list[dict]) -> None:
        p = self._path()
        text = json.dumps(items, indent=2, ensure_ascii=False)
        tmp = p.with_suffix(p.suffix + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, p)

    def query(
        self,
        *,
        category: str | None = None,
        q: str | None = None,
        limit: int = 500,
        offset: int = 0,
    ) -> tuple[list[dict], int]:
        """过滤查询, 返回 (items, total)。"""
        items = self.list_all()
        filtered = []
        kw = (q or "").strip().lower()
        for it in items:
            if category and it.get("category") != category:
                continue
            if kw:
                title = (it.get("title") or "").lower()
                summary = (it.get("summary") or "").lower()
                content = (it.get("content") or "").lower()
                tags = " ".join(it.get("tags", [])).lower()
                if kw not in title and kw not in summary and kw not in content and kw not in tags:
                    continue
            filtered.append(it)
        total = len(filtered)
        return filtered[offset : offset + limit], total

    def get_by_id(self, entry_id: str) -> dict | None:
        for it in self.list_all():
            if it.get("id") == entry_id:
                return it
        return None

    def categories_summary(self) -> list[dict]:
        """分类条目数统计。"""
        items = self.list_all()
        counts: dict[str, int] = {}
        for it in items:
            cat = it.get("category", "basics")
            counts[cat] = counts.get(cat, 0) + 1
        return [
            {"category": k, "label": CATEGORY_LABELS.get(k, k), "count": v}
            for k, v in sorted(counts.items())
        ]


